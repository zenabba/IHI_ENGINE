"""Generate the SYNTHETIC demo fleet used by the dashboard (data/demo/fleet.json).

    python scripts/make_demo_fleet.py            # rewrite data/demo/fleet.json
    python scripts/make_demo_fleet.py --check    # also print the resulting IHI per transformer

These are made-up transformers, not field data. Each one follows a "severity"
trajectory over five quarterly evaluations. For every parameter the script
picks a target sub-index from that severity and works backwards through the
thresholds in config/thresholds.yaml to a measured value, so the fleet spreads
across all health classes and a few units degrade fast enough to trip the
"accelerated" alert. The output is seeded, so it's reproducible.
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ihi.config import load_thresholds  # noqa: E402

OUTPUT = ROOT / "data" / "demo" / "fleet.json"
SEED = 2026

EVALUATION_DATES = [date(2025, 9, 15), date(2025, 12, 15), date(2026, 3, 16),
                    date(2026, 6, 15), date(2026, 9, 14)]

# id, substation, age at the last evaluation, severity at first and last evaluation
# (0 = like new, 1 = everything at its critical threshold)
PROFILES = [
    ("TR-01", "Poste 1", 22, 0.18, 0.22),
    ("TR-02", "Poste 1",  8, 0.02, 0.04),
    ("TR-03", "Poste 2", 31, 0.30, 0.52),
    ("TR-04", "Poste 2", 12, 0.10, 0.09),
    ("TR-05", "Poste 3", 36, 0.40, 0.72),
    ("TR-06", "Poste 3", 15, 0.26, 0.29),
    ("TR-07", "Poste 4", 41, 0.60, 0.97),
    ("TR-08", "Poste 4", 19, 0.21, 0.23),
]

# Parameters never measured on a given unit, to show missing-data handling.
NOT_MEASURED = {"TR-06": {"polarization_index"}}

# Combustible gases summed into TDCG (IEEE C57.104 definition).
COMBUSTIBLES = ("H2", "CH4", "C2H6", "C2H4", "C2H2", "CO")


def value_for_sub_index(si: float, spec: dict, rng: random.Random) -> float:
    """Invert the piecewise-linear normalization: a sub-index -> a plausible value."""
    normal, critical = spec["normal"], spec["critical"]
    low_good = spec["polarity"] == "low_good"
    if si >= 1:   # healthy side: somewhere comfortably inside the normal zone
        return normal * rng.uniform(0.5, 0.95) if low_good else normal * rng.uniform(1.05, 1.5)
    if si <= 0:   # past the critical threshold
        return critical * rng.uniform(1.0, 1.3) if low_good else critical * rng.uniform(0.7, 1.0)
    if low_good:
        return critical - si * (critical - normal)
    return critical + si * (normal - critical)


def round_for(unit: str | None, value: float) -> float:
    if unit == "ppm":
        return float(round(value))
    if unit in ("degC", "percent", "kV", "mN/m", "Mohm"):
        return round(value, 1)
    return round(value, 3)


def build_fleet() -> dict:
    rng = random.Random(SEED)
    families = load_thresholds()
    params = {p: spec for fam in families.values() for p, spec in (fam.get("parameters") or {}).items()}

    fleet = []
    for tid, substation, final_age, s_start, s_end in PROFILES:
        # How strongly each parameter reacts to this unit's severity (its "fault signature").
        sensitivity = {p: rng.uniform(0.6, 1.4) for p in params}
        skip = NOT_MEASURED.get(tid, set())
        measurements = []

        for k, day in enumerate(EVALUATION_DATES):
            progress = k / (len(EVALUATION_DATES) - 1)
            # Convex path: slow at first, faster at the end -> recent decline is the steepest.
            severity = s_start + (s_end - s_start) * progress ** 2
            values = {}
            for p, spec in params.items():
                if p in skip or p in ("age_years", "TDCG"):
                    continue
                si = 1 - severity * sensitivity[p] + rng.uniform(-0.02, 0.02)
                values[p] = round_for(spec.get("unit"), value_for_sub_index(si, spec, rng))

            values["TDCG"] = float(sum(values[g] for g in COMBUSTIBLES))
            years_before_last = (EVALUATION_DATES[-1] - day).days / 365.25
            values["age_years"] = round(final_age - years_before_last, 2)
            measurements.append({"timestamp": f"{day.isoformat()}T09:00:00", "values": values})

        fleet.append({"id": tid, "substation": substation, "measurements": measurements})

    return {"_comment": "SYNTHETIC demo data generated by scripts/make_demo_fleet.py - not field measurements",
            "transformers": fleet}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="print the resulting IHI per transformer")
    args = parser.parse_args()

    data = build_fleet()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")

    if args.check:
        from ihi.dashboard.service import FleetService
        from ihi.dashboard.store import FleetStore
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            service = FleetService(FleetStore(Path(tmp) / "fleet.json", OUTPUT))
            for s in service.fleet()["transformers"]:
                t = s["trend"]
                print(f"{s['id']}  IHI={s['ihi_percent']:5.1f}  {s['classification']['label']:<14}"
                      f" delta={t['delta_pt']:+5.1f}  rate={t['rate_pt_per_year']:+6.1f}/an"
                      f"  {'ACCELEREE' if t['accelerated'] else ''}")


if __name__ == "__main__":
    main()
